"""Run every CRUD operation against the real database: `python -m tracker.demo`.

Add --echo to see each SQL statement SQLAlchemy sends.
"""

import argparse
import uuid
from collections.abc import Sequence
from datetime import date, timedelta

from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from tracker import crud
from tracker.db import (
    create_database_if_missing,
    get_database_url,
    make_engine,
    make_session_factory,
    reset_schema,
)
from tracker.models import MemberRole, TaskStatus


def heading(title: str) -> None:
    print(f"\n=== {title} ===")


def print_board(session: Session, project_id: uuid.UUID) -> None:
    for task in crud.list_tasks(session, project_id=project_id):
        assignee = task.assignee.full_name if task.assignee else "(unassigned)"
        labels = ", ".join(label.name for label in task.labels) or "-"
        print(
            f"  P{task.priority}  {task.status:<11}  {task.title:<32}  "
            f"{assignee:<14}  [{labels}]"
        )


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Day 4 SQLAlchemy CRUD demo")
    parser.add_argument("--echo", action="store_true", help="print every SQL statement")
    args = parser.parse_args(argv)

    url = get_database_url()
    create_database_if_missing(url)
    engine = make_engine(url, echo=args.echo)
    reset_schema(engine)  # start from empty tables, so the demo can run again and again
    session_factory = make_session_factory(engine)
    today = date.today()

    heading("CREATE")
    # session_factory.begin(): one transaction for the whole block. It commits at
    # the end, or rolls back everything if any line raises.
    with session_factory.begin() as session:
        alice = crud.create_user(
            session, email="alice@example.com", full_name="Alice Rahman"
        )
        bob = crud.create_user(session, email="bob@example.com", full_name="Bob Karim")
        chitra = crud.create_user(
            session, email="chitra@example.com", full_name="Chitra Das"
        )
        project = crud.create_project(
            session,
            owner_id=alice.id,
            name="Website Redesign",
            description="New marketing site for Q4",
        )
        crud.add_member(session, project_id=project.id, user_id=bob.id)
        crud.add_member(
            session, project_id=project.id, user_id=chitra.id, role=MemberRole.ADMIN
        )
        bug = crud.create_label(
            session, project_id=project.id, name="bug", color="#D73A4A"
        )
        design = crud.create_label(
            session, project_id=project.id, name="design", color="#A2EEEF"
        )
        homepage = crud.create_task(
            session,
            project_id=project.id,
            created_by=alice.id,
            title="Design new homepage",
            priority=2,
            due_date=today + timedelta(days=3),
            assignee_id=chitra.id,
        )
        links = crud.create_task(
            session,
            project_id=project.id,
            created_by=alice.id,
            title="Fix broken links",
            priority=1,
            due_date=today - timedelta(days=1),
            assignee_id=bob.id,
        )
        about = crud.create_task(
            session,
            project_id=project.id,
            created_by=alice.id,
            title="Write content for About page",
            due_date=today - timedelta(days=2),
        )
        crud.add_label_to_task(session, task_id=homepage.id, label_id=design.id)
        crud.add_label_to_task(session, task_id=links.id, label_id=bug.id)
        crud.add_comment(
            session, task_id=links.id, author_id=bob.id, body="Found 12 so far."
        )

        # Keep plain ids for later blocks. The objects themselves expire when this
        # block commits, and can't be reloaded once their session has closed.
        alice_id, bob_id, chitra_id = alice.id, bob.id, chitra.id
        project_id, design_id = project.id, design.id
        homepage_id, links_id, about_id = homepage.id, links.id, about.id
        print("3 users, 1 project, 2 labels, 3 tasks and 1 comment")
        print(f"Alice's id was generated by the database (uuidv7): {alice_id}")

    heading("READ")
    with session_factory() as session:
        print_board(session, project_id)
        found = crud.get_user_by_email(session, "ALICE@example.com")
        print(f"get_user_by_email('ALICE@example.com') -> {found}")
        projects = crud.list_projects_for_user(session, bob_id)
        print(f"Projects Bob is in: {[p.name for p in projects]}")
        details = crud.get_task_details(session, links_id)
        for comment in details.comments:
            print(f"{comment.author.full_name} on {details.title!r}: {comment.body!r}")

    heading("UPDATE")
    with session_factory.begin() as session:
        task = crud.update_task(
            session, links_id, {"title": "Fix broken links everywhere"}
        )
        print(f"Renamed task -> {task.title!r}")
        crud.set_task_status(session, homepage_id, TaskStatus.IN_PROGRESS)
        crud.assign_task(session, about_id, alice_id)
        user = crud.update_user(session, bob_id, {"full_name": "Bob K. Karim"})
        print(
            f"Bob renamed. created_at {user.created_at:%H:%M:%S.%f}, "
            f"updated_at {user.updated_at:%H:%M:%S.%f} (set by the trigger)"
        )

    heading("TRANSACTION: two writes, one unit of work")
    with session_factory.begin() as session:
        crud.complete_task(
            session, task_id=links_id, user_id=bob_id, note="All links fixed."
        )
    print("Committed: the task is done AND the comment was saved")

    try:
        with session_factory.begin() as session:
            # A blank note breaks the CHECK on comments.body...
            crud.complete_task(
                session, task_id=homepage_id, user_id=chitra_id, note="   "
            )
    except IntegrityError as error:
        print(f"Rolled back: {str(error.orig).splitlines()[0]}")
    with session_factory() as session:
        status = crud.get_task(session, homepage_id).status
        # ...so the status change that ran before it was rolled back too.
        print(f"'Design new homepage' is still {status!r}, not 'done'")

    heading("SAVEPOINT: undo one step, keep the rest")
    with session_factory.begin() as session:
        crud.add_comment(
            session, task_id=homepage_id, author_id=chitra_id, body="Wireframes done."
        )
        try:
            with session.begin_nested():  # SAVEPOINT
                crud.create_label(session, project_id=project_id, name="bug")
        except IntegrityError:
            print("Duplicate label 'bug' rolled back to the savepoint")
    with session_factory() as session:
        count = len(crud.list_comments(session, homepage_id))
        print(f"...and the comment before it was still committed ({count} comment)")

    heading("DELETE")
    with session_factory.begin() as session:
        crud.delete_task(session, about_id)  # soft delete: sets deleted_at
        crud.delete_label(session, design_id)  # hard delete; task_labels rows too
        # Hard delete: the database's ON DELETE SET NULL unassigns Chitra's tasks.
        crud.remove_member(session, project_id=project_id, user_id=chitra_id)
    with session_factory() as session:
        print("Board after deleting 'About page' and label 'design', and removing")
        print("Chitra from the project (her task is now unassigned):")
        print_board(session, project_id)

    with session_factory.begin() as session:
        crud.restore_task(session, about_id)
    with session_factory() as session:
        print("Board after restoring the soft-deleted task:")
        print_board(session, project_id)

    engine.dispose()


if __name__ == "__main__":
    main()
