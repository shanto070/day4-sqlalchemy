def test_list_tasks_filters_and_hides_deleted(
    session: Session, project: Project, task: Task, alice: User, bob: User
) -> None:
    other = crud.create_task(
        session, project_id=project.id, created_by=alice.id, title="About", priority=2
    )
    crud.set_task_status(session, other.id, TaskStatus.IN_PROGRESS)

    assert crud.list_tasks(session, project_id=project.id) == [other, task]
    todo = crud.list_tasks(session, project_id=project.id, status=TaskStatus.TODO)
    assert todo == [task]
    assert crud.list_tasks(session, project_id=project.id, assignee_id=bob.id) == [task]
    crud.delete_task(session, task.id)
    assert crud.list_tasks(session, project_id=project.id) == [other]


def test_soft_delete_and_restore_task(session: Session, task: Task) -> None:
    crud.delete_task(session, task.id)
    with pytest.raises(crud.NotFoundError):
        crud.get_task(session, task.id)
    crud.restore_task(session, task.id)
    assert crud.get_task(session, task.id) is task


def test_removing_a_member_unassigns_their_tasks(
    session: Session, project: Project, task: Task, bob: User
) -> None:
    assert task.assignee_id == bob.id
    crud.remove_member(session, project_id=project.id, user_id=bob.id)
    # ON DELETE SET NULL (assignee_id) ran inside PostgreSQL. remove_member()
    # expired the session, so this reads the new value from the database.
    assert task.assignee_id is None


def test_task_details_load_in_three_queries_and_skip_deleted_comments(
    session: Session, task: Task, alice: User, bob: User, bug: Label
) -> None:
    crud.add_label_to_task(session, task_id=task.id, label_id=bug.id)
    crud.add_comment(session, task_id=task.id, author_id=bob.id, body="On it")
    typo = crud.add_comment(session, task_id=task.id, author_id=alice.id, body="Tpyo")
    crud.delete_comment(session, typo.id)
    # Read the id first: after expire_all(), even task.id would cost a SELECT.
    task_id = task.id
    session.expire_all()  # start from an empty identity map, like a new request

    with QueryCounter(session) as counter:
        details = crud.get_task_details(session, task_id)
        comments = [(c.author.full_name, c.body) for c in details.comments]
        labels = [label.name for label in details.labels]
        people = (details.creator.full_name, details.assignee)
    assert counter.count == 3
    assert comments == [("Bob Karim", "On it")]
    assert labels == ["bug"]
    assert people == ("Alice Rahman", bob)


