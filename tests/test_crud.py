# -------------------------------------------------------------------- transactions


def test_complete_task_commits_both_writes(
    session_factory: sessionmaker[Session], task: Task, bob: User
) -> None:
    with session_factory.begin() as tx:
        crud.complete_task(tx, task_id=task.id, user_id=bob.id, note="Fixed")
    with session_factory() as check:
        assert crud.get_task(check, task.id).status == TaskStatus.DONE
        assert len(crud.list_comments(check, task.id)) == 1


def test_failed_unit_of_work_rolls_back_every_write(
    session_factory: sessionmaker[Session], task: Task, bob: User
) -> None:
    with pytest.raises(IntegrityError), session_factory.begin() as tx:
        crud.complete_task(tx, task_id=task.id, user_id=bob.id, note="   ")
    with session_factory() as check:
        # The status change ran first, but it was rolled back with the comment.
        assert crud.get_task(check, task.id).status == TaskStatus.TODO
        assert crud.list_comments(check, task.id) == []
