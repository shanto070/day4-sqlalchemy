"""CRUD tests against the real Day 3 schema.

Each test runs inside a transaction that is rolled back afterwards (conftest.py).
`with (pytest.raises(...), session.begin_nested()):` puts a statement that is
meant to fail inside a SAVEPOINT, so only that statement is undone.
"""

from datetime import date

import pytest
from sqlalchemy import inspect
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session, sessionmaker

from tracker import crud
from tracker.models import Label, MemberRole, Project, Task, TaskStatus, User
from tracker.pitfalls import QueryCounter


@pytest.fixture
def task(session: Session, project: Project, alice: User, bob: User) -> Task:
    return crud.create_task(
        session,
        project_id=project.id,
        created_by=alice.id,
        title="Fix broken links",
        assignee_id=bob.id,
    )


@pytest.fixture
def bug(session: Session, project: Project) -> Label:
    return crud.create_label(
        session, project_id=project.id, name="bug", color="#D73A4A"
    )


# --------------------------------------------------------------------------- users


def test_create_user_gets_id_and_timestamps_from_the_database(alice: User) -> None:
    assert alice.id.version == 7  # uuidv7(), generated by PostgreSQL
    assert alice.created_at.tzinfo is not None  # timestamptz
    assert alice.deleted_at is None


def test_get_user_by_email_ignores_case(session: Session, alice: User) -> None:
    # Same row, same session -> the identity map hands back the very same object.
    assert crud.get_user_by_email(session, "ALICE@Example.com") is alice


def test_duplicate_email_is_rejected_ignoring_case(
    session: Session, alice: User
) -> None:
    with (
        pytest.raises(IntegrityError, match="users_email_active_uq"),
        session.begin_nested(),
    ):
        crud.create_user(session, email="ALICE@example.com", full_name="Alice 2")


def test_update_user_changes_only_the_given_fields(
    session: Session, alice: User
) -> None:
    crud.update_user(session, alice.id, {"full_name": "Alice R."})
    session.expire(alice)  # drop the cached values and reload from the database
    assert (alice.full_name, alice.email) == ("Alice R.", "alice@example.com")


def test_deleted_user_is_hidden_and_their_email_is_free_again(
    session: Session, alice: User, bob: User
) -> None:
    crud.delete_user(session, alice.id)
    with pytest.raises(crud.NotFoundError):
        crud.get_user(session, alice.id)
    assert crud.get_user_by_email(session, "alice@example.com") is None
    assert crud.list_users(session) == [bob]
    # The unique index only covers active users (WHERE deleted_at IS NULL).
    crud.create_user(session, email="alice@example.com", full_name="New Alice")


